-- Run once in the CyberShield Supabase SQL Editor before deploying Windows agent support.

CREATE TABLE IF NOT EXISTS public.endpoint_agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.endpoint_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL REFERENCES public.endpoint_agents(id) ON DELETE CASCADE,
    source_ref TEXT NOT NULL,
    event_time TIMESTAMPTZ NOT NULL,
    channel TEXT NOT NULL,
    event_id INTEGER NOT NULL,
    source_ip TEXT,
    source_port INTEGER,
    destination_ip TEXT,
    destination_port INTEGER,
    network_protocol TEXT,
    network_direction TEXT,
    event_name TEXT NOT NULL,
    alert_level TEXT,
    alert_text TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(agent_id, source_ref)
);

ALTER TABLE public.endpoint_events ADD COLUMN IF NOT EXISTS source_port INTEGER;
ALTER TABLE public.endpoint_events ADD COLUMN IF NOT EXISTS destination_ip TEXT;
ALTER TABLE public.endpoint_events ADD COLUMN IF NOT EXISTS destination_port INTEGER;
ALTER TABLE public.endpoint_events ADD COLUMN IF NOT EXISTS network_protocol TEXT;
ALTER TABLE public.endpoint_events ADD COLUMN IF NOT EXISTS network_direction TEXT;

CREATE INDEX IF NOT EXISTS endpoint_agents_user_idx
    ON public.endpoint_agents(user_id, revoked_at);
CREATE INDEX IF NOT EXISTS endpoint_events_agent_created_idx
    ON public.endpoint_events(agent_id, created_at DESC);
CREATE INDEX IF NOT EXISTS endpoint_events_failed_login_idx
    ON public.endpoint_events(agent_id, event_id, source_ip, created_at);

ALTER TABLE public.endpoint_agents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.endpoint_events ENABLE ROW LEVEL SECURITY;
