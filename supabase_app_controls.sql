CREATE TABLE IF NOT EXISTS public.admin_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_activity_created_idx
    ON public.admin_activity (created_at DESC);

ALTER TABLE public.admin_activity ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.scan_rate_limits (
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    window_start TIMESTAMPTZ NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, window_start)
);

CREATE INDEX IF NOT EXISTS scan_rate_limits_window_idx
    ON public.scan_rate_limits (window_start);

ALTER TABLE public.scan_rate_limits ENABLE ROW LEVEL SECURITY;
