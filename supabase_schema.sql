-- CyberShield tables for the Supabase PostgreSQL database.
-- Safe to run on a new, empty CyberShield project.

CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'user')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
    ON public.users (LOWER(email));

CREATE TABLE IF NOT EXISTS public.scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    module TEXT NOT NULL,
    target TEXT NOT NULL,
    risk TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_hidden_at TIMESTAMPTZ,
    analysis_details TEXT NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS public.admin_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.scan_rate_limits (
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    window_start TIMESTAMPTZ NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, window_start)
);

ALTER TABLE public.scans
    ADD COLUMN IF NOT EXISTS user_hidden_at TIMESTAMPTZ;
ALTER TABLE public.scans
    ADD COLUMN IF NOT EXISTS analysis_details TEXT NOT NULL DEFAULT '{}';

CREATE INDEX IF NOT EXISTS scans_user_created_idx
    ON public.scans (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS admin_activity_created_idx
    ON public.admin_activity (created_at DESC);
CREATE INDEX IF NOT EXISTS scan_rate_limits_window_idx
    ON public.scan_rate_limits (window_start);

-- The Flask backend accesses these tables through a private PostgreSQL
-- connection. Keep the REST Data API disabled unless RLS policies and grants
-- are reviewed for a future API-based access path.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_activity ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scan_rate_limits ENABLE ROW LEVEL SECURITY;
